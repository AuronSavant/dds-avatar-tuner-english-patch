FONTS = {'3x5': F35, '4x7': F47, '5x7': F57}


def text_width(text, font, spacing=1):
    f = FONTS[font]
    return sum(len(f[c][0]) for c in text) + spacing * (len(text) - 1)


def draw(img, x, y, text, font, color, spacing=1, bold=False):
    """Draw onto a PIL 'P' image with palette index `color`."""
    f = FONTS[font]
    for c in text:
        g = f[c]
        for gy, row in enumerate(g):
            for gx, px in enumerate(row):
                if px == '#':
                    img.putpixel((x + gx, y + gy), color)
                    if bold:
                        img.putpixel((x + gx + 1, y + gy), color)
        x += len(g[0]) + spacing + (1 if bold else 0)
    return x
